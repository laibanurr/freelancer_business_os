import 'dart:async';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:freelancer_business_os/models/project.dart';
import 'package:freelancer_business_os/models/time_entry.dart';
import 'package:freelancer_business_os/providers/repositories_provider/time_entry_repo_provider.dart';
import 'package:freelancer_business_os/providers/service_provider/ai_ser_provider.dart';
import 'package:freelancer_business_os/providers/state_provider/theme_provider.dart';
import 'package:freelancer_business_os/providers/stream_provider/entries_for_project_provider.dart';
const _primaryIndigo = Color(0xFF4F46E5);
class TimeEntriesScreen extends ConsumerStatefulWidget {
  final Project project;
  const TimeEntriesScreen({
    super.key,
    required this.project,
  });
  @override
  ConsumerState<TimeEntriesScreen> createState() => _TimeEntriesScreenState();
}
class _TimeEntriesScreenState extends ConsumerState<TimeEntriesScreen> {
  Timer? _ticker;
  bool _isProcessingAction = false;
  @override
  void dispose() {
    _ticker?.cancel();
    super.dispose();
  }
  void _ensureTicking(bool shouldTick) {
    if (shouldTick && _ticker == null) {
      _ticker = Timer.periodic(const Duration(seconds: 1), (_) {
        if (mounted) setState(() {});
      });
    } else if (!shouldTick && _ticker != null) {
      _ticker!.cancel();
      _ticker = null;
    }
  }
  String _formatDuration(Duration d) {
    String twoDigits(int n) => n.toString().padLeft(2, '0');
    final hours = twoDigits(d.inHours);
    final minutes = twoDigits(d.inMinutes.remainder(60));
    final seconds = twoDigits(d.inSeconds.remainder(60));
    return '$hours:$minutes:$seconds';
  }
  Future<void> _generateAiWorkSummary(double hoursLogged) async {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (_) => const Center(
        child: CircularProgressIndicator(color: _primaryIndigo),
      ),
    );
    String summary = '';
    bool usedFallback = false;
    try {
      final aiService = ref.read(aiServiceProvider);
      final hoursString = hoursLogged.toStringAsFixed(1);
      summary = await aiService.auditInvoiceSummary(
        hoursString,
        'Project: ${widget.project.projectName}. ${widget.project.projectDescription ?? ""}',
      ).timeout(const Duration(seconds: 4));
    } catch (e) {
      debugPrint('Gemini timed out or blocked; utilizing smart local template: $e');
      usedFallback = true;
      final hoursStr = hoursLogged.toStringAsFixed(1);
      final projectName = widget.project.projectName;
      summary = 'Completed $hoursStr billable hours dedicated to $projectName '
          'milestone delivery, architecture implementation, and quality assurance testing.';
    }
    if (!mounted) return;
    Navigator.pop(context); 
    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        title: Row(
          children: [
            const Icon(Icons.auto_awesome, color: _primaryIndigo, size: 20),
            const SizedBox(width: 8),
            Text(
              usedFallback ? 'Invoice Line Item (Template)' : 'AI Invoice Line Item',
              style: const TextStyle(fontSize: 16, fontWeight: FontWeight.bold),
            ),
          ],
        ),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              usedFallback
                  ? 'Compiled based on your project deliverables and $hoursLogged hrs logged:'
                  : 'Generated by Gemini AI based on your contract roadmap:',
              style: const TextStyle(color: Colors.grey, fontSize: 12),
            ),
            const SizedBox(height: 12),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: _primaryIndigo.withValues(alpha: 0.05),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: _primaryIndigo.withValues(alpha: 0.15)),
              ),
              child: Text(
                summary,
                style: const TextStyle(fontSize: 14, height: 1.4),
              ),
            ),
          ],
        ),
        actions: [
          TextButton.icon(
            onPressed: () {
              Clipboard.setData(ClipboardData(text: summary));
              Navigator.pop(ctx);
              if (mounted) {
                ScaffoldMessenger.of(context).showSnackBar(
                  const SnackBar(
                    content: Text('Copied description to clipboard!'),
                    backgroundColor: _primaryIndigo,
                    behavior: SnackBarBehavior.floating,
                  ),
                );
              }
            },
            icon: const Icon(Icons.copy_rounded, size: 16),
            label: const Text('Copy to Clipboard'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }
  @override
  Widget build(BuildContext context) {
    final entriesAsync =
        ref.watch(timeEntriesForProjectProvider(widget.project.id));
    final isDarkMode = ref.watch(themeProvider);
    final backgroundColor =
        isDarkMode ? const Color(0xFF0F172A) : const Color(0xFFF8FAFC);
    final cardColor = isDarkMode ? const Color(0xFF1E293B) : Colors.white;
    final textColor = isDarkMode ? Colors.white : Colors.black87;
    return Scaffold(
      backgroundColor: backgroundColor,
      appBar: AppBar(
        backgroundColor: backgroundColor,
        elevation: 0,
        leading: IconButton(
          onPressed: () => Navigator.pop(context),
          icon: Icon(
            Icons.arrow_back_ios_new,
            size: 20,
            color: isDarkMode ? Colors.white70 : Colors.black87,
          ),
        ),
        title: Text(
          widget.project.projectName,
          style: TextStyle(
            color: textColor,
            fontWeight: FontWeight.bold,
            fontSize: 20,
          ),
        ),
      ),
      body: entriesAsync.when(
        loading: () => const Center(
          child: CircularProgressIndicator(color: _primaryIndigo),
        ),
        error: (error, stack) => Center(
          child: Text(
            'Error: $error',
            style: const TextStyle(color: Colors.redAccent),
          ),
        ),
        data: (entries) {
          TimeEntry? runningEntry;
          for (final e in entries) {
            if (e.endTime == null) {
              runningEntry = e;
              break;
            }
          }
          WidgetsBinding.instance.addPostFrameCallback((_) {
            if (mounted) {
              _ensureTicking(runningEntry != null);
            }
          });
          final pastEntries =
              entries.where((e) => e.endTime != null).toList();
          final isTimerRunning = runningEntry != null;
          return Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              Container(
                margin: const EdgeInsets.all(20),
                padding:
                    const EdgeInsets.symmetric(vertical: 32, horizontal: 24),
                decoration: BoxDecoration(
                  color: isTimerRunning
                      ? _primaryIndigo.withValues(alpha: 0.03)
                      : cardColor,
                  borderRadius: BorderRadius.circular(24),
                  border: Border.all(
                    color: isTimerRunning
                        ? _primaryIndigo.withValues(alpha: 0.2)
                        : Colors.grey.withValues(alpha: 0.15),
                    width: 1.5,
                  ),
                ),
                child: Column(
                  children: [
                    Text(
                      isTimerRunning
                          ? 'ACTIVE TRACKING SESSION'
                          : 'TIMER DISENGAGED',
                      style: TextStyle(
                        color:
                            isTimerRunning ? _primaryIndigo : Colors.grey,
                        fontSize: 12,
                        fontWeight: FontWeight.bold,
                        letterSpacing: 1.5,
                      ),
                    ),
                    const SizedBox(height: 16),
                    Text(
                      isTimerRunning
                          ? _formatDuration(
                              DateTime.now().difference(runningEntry.startTime),
                            )
                          : '00:00:00',
                      style: TextStyle(
                        fontSize: 42,
                        fontWeight: FontWeight.bold,
                        color: isTimerRunning ? _primaryIndigo : textColor,
                        letterSpacing: 1.0,
                      ),
                    ),
                    const SizedBox(height: 24),
                    SizedBox(
                      width: 160,
                      child: ElevatedButton(
                        onPressed: _isProcessingAction
                            ? null
                            : () async {
                                setState(() => _isProcessingAction = true);
                                final repo =
                                    ref.read(timeEntryRepositoryProvider);
                                try {
                                  if (runningEntry != null) {
                                    final updated = runningEntry.copyWith(
                                      endTime: DateTime.now(),
                                    );
                                    await repo.updateTimeEntry(updated);
                                  } else {
                                    final entry = TimeEntry(
                                      id: repo.newTimeEntryId(),
                                      projectId: widget.project.id,
                                      startTime: DateTime.now(),
                                      endTime: null,
                                    );
                                    await repo.addTimeEntry(entry);
                                  }
                                } catch (e) {
                                  debugPrint('Timer toggle error: $e');
                                  if (mounted) {
                                    ScaffoldMessenger.of(context).showSnackBar(
                                      SnackBar(
                                        content: Text('Error updating timer: $e'),
                                        backgroundColor: Colors.redAccent,
                                      ),
                                    );
                                  }
                                } finally {
                                  if (mounted) {
                                    setState(() => _isProcessingAction = false);
                                  }
                                }
                              },
                        style: ElevatedButton.styleFrom(
                          backgroundColor: isTimerRunning
                              ? Colors.redAccent
                              : _primaryIndigo,
                          foregroundColor: Colors.white,
                          elevation: 0,
                          padding: const EdgeInsets.symmetric(vertical: 14),
                          shape: RoundedRectangleBorder(
                            borderRadius: BorderRadius.circular(28),
                          ),
                        ),
                        child: _isProcessingAction
                            ? const SizedBox(
                                height: 20,
                                width: 20,
                                child: CircularProgressIndicator(
                                  strokeWidth: 2,
                                  color: Colors.white,
                                ),
                              )
                            : Row(
                                mainAxisAlignment: MainAxisAlignment.center,
                                children: [
                                  Icon(
                                    isTimerRunning
                                        ? Icons.stop_rounded
                                        : Icons.play_arrow_rounded,
                                    size: 20,
                                  ),
                                  const SizedBox(width: 6),
                                  Text(
                                    isTimerRunning ? 'Stop' : 'Start',
                                    style: const TextStyle(
                                      fontWeight: FontWeight.bold,
                                      fontSize: 16,
                                    ),
                                  ),
                                ],
                              ),
                      ),
                    ),
                  ],
                ),
              ),
              Padding(
                padding: const EdgeInsets.symmetric(
                    horizontal: 24.0, vertical: 8.0),
                child: Text(
                  'Completed Sessions History',
                  style: TextStyle(
                    fontSize: 16,
                    fontWeight: FontWeight.bold,
                    color: textColor,
                  ),
                ),
              ),
              Expanded(
                child: pastEntries.isEmpty
                    ? Center(
                        child: Text(
                          'No history recorded yet.',
                          style: TextStyle(
                            color: Colors.grey.withValues(alpha: 0.8),
                            fontSize: 14,
                          ),
                        ),
                      )
                    : ListView.separated(
                        padding: const EdgeInsets.only(
                            left: 20, right: 20, top: 8, bottom: 24),
                        separatorBuilder: (_, __) =>
                            const SizedBox(height: 12),
                        itemCount: pastEntries.length,
                        itemBuilder: (context, index) {
                          final entry = pastEntries[index];
                          final duration =
                              entry.endTime!.difference(entry.startTime);
                          final hoursDouble = duration.inMinutes / 60.0;
                          return Container(
                            padding: const EdgeInsets.all(14),
                            decoration: BoxDecoration(
                              color: cardColor,
                              borderRadius: BorderRadius.circular(16),
                              border: Border.all(
                                color: isDarkMode
                                    ? Colors.white.withValues(alpha: 0.08)
                                    : Colors.grey.withValues(alpha: 0.15),
                                width: 1,
                              ),
                            ),
                            child: Row(
                              children: [
                                Container(
                                  padding: const EdgeInsets.all(10),
                                  decoration: BoxDecoration(
                                    color: isDarkMode
                                        ? Colors.white.withValues(alpha: 0.05)
                                        : Colors.grey.withValues(alpha: 0.05),
                                    shape: BoxShape.circle,
                                  ),
                                  child: Icon(
                                    Icons.history_toggle_off,
                                    color: isDarkMode
                                        ? Colors.grey
                                        : Colors.grey.shade600,
                                    size: 20,
                                  ),
                                ),
                                const SizedBox(width: 16),
                                Expanded(
                                  child: Column(
                                    crossAxisAlignment:
                                        CrossAxisAlignment.start,
                                    children: [
                                      Text(
                                        '${entry.startTime.month}/${entry.startTime.day}/${entry.startTime.year}',
                                        style: TextStyle(
                                          fontWeight: FontWeight.bold,
                                          fontSize: 15,
                                          color: textColor,
                                        ),
                                      ),
                                      const SizedBox(height: 4),
                                      Text(
                                        '${hoursDouble.toStringAsFixed(1)} hrs logged (${_formatDuration(duration)})',
                                        style: const TextStyle(
                                          color: Colors.grey,
                                          fontSize: 13,
                                        ),
                                      ),
                                    ],
                                  ),
                                ),
                                IconButton(
                                  icon: const Icon(
                                    Icons.auto_awesome,
                                    color: _primaryIndigo,
                                    size: 20,
                                  ),
                                  tooltip: 'Generate AI Invoice Description',
                                  onPressed: () =>
                                      _generateAiWorkSummary(hoursDouble),
                                ),
                              ],
                            ),
                          );
                        },
                      ),
              ),
            ],
          );
        },
      ),
    );
  }
}